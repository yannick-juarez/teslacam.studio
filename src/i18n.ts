export type Language = 'fr' | 'en'
const formatterCache = new Map<string, Intl.DateTimeFormat>()

void i18n.use(initReactI18next).init({
  resources: { fr: { translation: fr }, en: { translation: en } },
  lng: localStorage.getItem('teslacam-language') === 'en' ? 'en' : 'fr',
  fallbackLng: 'fr',
  interpolation: { escapeValue: false },
  initAsync: false,
})

export function formatDate(timestamp: number, options: Intl.DateTimeFormatOptions): string {
  const locale = i18n.language === 'en' ? 'en-US' : 'fr-FR'
  const key = `${locale}:${JSON.stringify(options)}`
  let formatter = formatterCache.get(key)
  if (!formatter) {
    formatter = new Intl.DateTimeFormat(locale, options)
    formatterCache.set(key, formatter)
  }
  return formatter.format(timestamp)
}

export function formatTime(timestamp: number): string {
  return formatDate(timestamp, { hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23' })
}

export function changeLanguage(language: Language): void {
  localStorage.setItem('teslacam-language', language)
  void i18n.changeLanguage(language)
}

export default i18n